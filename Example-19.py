str1 = "Hello Python"

# Slicing examples
print("Original string:", str1)
print("str1[0:5]:", str1[0:5])        # 'Hello'
print("str1[6:]:", str1[6:])          # 'Python'
print("str1[:5]:", str1[:5])          # 'Hello'
print("str1[-6:]:", str1[-6:])        # 'Python'
print("str1[::2]:", str1[::2])        # Every second character
print("str1[::-1]:", str1[::-1])      # Reversed string
